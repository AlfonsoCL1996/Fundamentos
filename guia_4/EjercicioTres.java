/*Hacer un programa para mostrar los números del 1 al 10. No se debe realizar ningún pedido de datos. */

package guia_4;

public class EjercicioTres {
    public static void main(String[] args) {
        int numero = 0;
        for (int i=0; i<=9; i++) {
            numero += 1;
            System.out.println(numero);
        }
    }
}
