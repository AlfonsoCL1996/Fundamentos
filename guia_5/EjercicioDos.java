/* Hacer un programa para mostrar los números del 10 al 1. No se debe realizar ningún pedido de datos.
USANDO WHILE. */

package guia_5;

public class EjercicioDos {
    public static void main(String[] args) {
        int n = 10;
        while (n>=1) {
            System.out.println(n);
            n--;
        }
    }
}
