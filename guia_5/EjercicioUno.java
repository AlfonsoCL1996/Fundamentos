/* Hacer un programa para mostrar los números del 1 al 10. No se debe realizar ningún pedido de datos.
USANDO WHILE. */

package guia_5;

public class EjercicioUno {
    public static void main(String[] args) {
        int n = 0;
        while (n<10) {
            n = n+1;
            System.out.println(n);
        }
    }
}
